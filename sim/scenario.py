"""Traffic-side-neutral scenario specs and their mirrored OpenDRIVE / OpenSCENARIO files.

A spec names lanes by INDEX counted from the centre line of the carriageway:
    1 = inner lane (overtaking lane), 2 = middle lane, 3 = outer lane (kerb side).
The same spec is written twice:
    RHT: road rule="RHT", own direction uses lanes -1, -2, -3 (right of the reference line, t < 0)
    LHT: road rule="LHT", own direction uses lanes +1, +2, +3 (left of the reference line, t > 0)
Both worlds drive in +x (= +s).  The LHT world is the RHT world mirrored about the reference line
(y -> -y); nothing else changes.  esmini v3.10.2 honours the OpenDRIVE rule attribute (checked: in an
LHT road a vehicle in lane +2 drives in +s, a vehicle in lane -2 drives in -s).
"""
from __future__ import annotations

import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

SCEN_DIR = Path(__file__).resolve().parents[1] / "scenarios"
LANE_W = 3.5
N_LANES = 3
ROAD_LEN = 3000.0
SIDES = ("RHT", "LHT")

# bounding boxes (reference point = rear axle centre, as in esmini's default vehicles)
GEOM = {"car": {"cx": 1.4, "length": 4.7, "width": 1.85, "height": 1.5},
        "motorbike": {"cx": 0.7, "length": 2.0, "width": 0.8, "height": 1.4}}


def lane_id(index: int, side: str) -> int:
    if not 1 <= index <= N_LANES:
        raise ValueError(f"lane index {index}")
    return -index if side == "RHT" else index


def lane_t(index: int, side: str) -> float:
    """Lateral position of the lane centre (t, positive to the left of the reference line)."""
    t = (index - 0.5) * LANE_W
    return -t if side == "RHT" else t


def mirror_lane_id(lid: int) -> int:
    return -lid


@dataclass(frozen=True)
class Event:
    t: float                  # trigger time (SimulationTimeCondition greaterOrEqual)
    kind: str                 # "speed" | "lane"
    value: float              # target speed [m/s] or target lane INDEX
    param: float              # speed: rate [m/s2] (0 = step); lane: duration [s]


@dataclass(frozen=True)
class Actor:
    name: str
    category: str             # "car" | "motorbike"
    lane: int                 # lane index
    s0: float
    v0: float                 # m/s
    events: tuple = ()


@dataclass(frozen=True)
class Spec:
    case_id: str
    family: str
    description: str
    ego_lane: int
    ego_s0: float
    ego_v0: float
    actors: tuple
    t_end: float = 30.0
    notes: dict = field(default_factory=dict)


# ----------------------------------------------------------------------------- OpenDRIVE
def write_road(side: str) -> Path:
    root = ET.Element("OpenDRIVE")
    ET.SubElement(root, "header", revMajor="1", revMinor="6", name=f"dual_3lane_{side}", version="1.0",
                  date="2026-10-28T00:00:00")
    road = ET.SubElement(root, "road", name=f"dual_3lane_{side}", length=f"{ROAD_LEN}", id="1", junction="-1",
                         rule=side)
    ET.SubElement(road, "link")
    pv = ET.SubElement(road, "planView")
    geo = ET.SubElement(pv, "geometry", s="0.0", x="0.0", y="0.0", hdg="0.0", length=f"{ROAD_LEN}")
    ET.SubElement(geo, "line")
    ep = ET.SubElement(road, "elevationProfile")
    ET.SubElement(ep, "elevation", s="0.0", a="0.0", b="0.0", c="0.0", d="0.0")
    ET.SubElement(road, "lateralProfile")
    sec = ET.SubElement(ET.SubElement(road, "lanes"), "laneSection", s="0.0")
    for grp, sign in (("left", 1), ("right", -1)):
        g = ET.SubElement(sec, grp)
        ids = range(N_LANES, 0, -1) if sign > 0 else range(1, N_LANES + 1)
        for k in ids:
            lane = ET.SubElement(g, "lane", id=str(sign * k), type="driving", level="false")
            ET.SubElement(lane, "link")
            ET.SubElement(lane, "width", sOffset="0.0", a=f"{LANE_W}", b="0.0", c="0.0", d="0.0")
            mark = "solid" if k == N_LANES else "broken"
            ET.SubElement(lane, "roadMark", sOffset="0.0", type=mark, weight="standard", color="standard",
                          width="0.15")
        if grp == "left":
            c = ET.SubElement(sec, "center")
            lane0 = ET.SubElement(c, "lane", id="0", type="none", level="false")
            ET.SubElement(lane0, "link")
            ET.SubElement(lane0, "roadMark", sOffset="0.0", type="solid solid", weight="standard",
                          color="standard", width="0.15")
    ET.indent(root, space="  ")
    path = SCEN_DIR / f"road_{side}.xodr"
    SCEN_DIR.mkdir(parents=True, exist_ok=True)
    comment = (f"\n  Straight 3 km dual carriageway, 3 lanes x {LANE_W} m per direction, rule=\"{side}\".\n"
               f"  Generated by scripts/make_scenarios.py (sim/scenario.py).  Lane width and markings are\n"
               f"  project choices.\n")
    xml = ET.tostring(root, encoding="unicode")
    path.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<!--' + comment + '-->\n' + xml + "\n",
                    encoding="utf-8")
    return path


# ----------------------------------------------------------------------------- OpenSCENARIO
def _vehicle(parent, name, category):
    g = GEOM[category]
    veh = ET.SubElement(parent, "Vehicle", name=name, vehicleCategory=category)
    ET.SubElement(veh, "ParameterDeclarations")
    ET.SubElement(veh, "Performance", maxSpeed="70.0", maxAcceleration="10.0", maxDeceleration="10.0")
    bb = ET.SubElement(veh, "BoundingBox")
    ET.SubElement(bb, "Center", x=f"{g['cx']}", y="0.0", z=f"{g['height'] / 2}")
    ET.SubElement(bb, "Dimensions", width=f"{g['width']}", length=f"{g['length']}", height=f"{g['height']}")
    ax = ET.SubElement(veh, "Axles")
    ET.SubElement(ax, "FrontAxle", maxSteering="0.5", wheelDiameter="0.6", trackWidth="1.6",
                  positionX=f"{2 * g['cx']}", positionZ="0.3")
    ET.SubElement(ax, "RearAxle", maxSteering="0.0", wheelDiameter="0.6", trackWidth="1.6", positionX="0.0",
                  positionZ="0.3")
    ET.SubElement(veh, "Properties")


def _speed_action(parent, v, rate):
    la = ET.SubElement(ET.SubElement(parent, "LongitudinalAction"), "SpeedAction")
    if rate > 0:
        ET.SubElement(la, "SpeedActionDynamics", dynamicsShape="linear", value=f"{rate}", dynamicsDimension="rate")
    else:
        ET.SubElement(la, "SpeedActionDynamics", dynamicsShape="step", value="0.0", dynamicsDimension="time")
    ET.SubElement(ET.SubElement(la, "SpeedActionTarget"), "AbsoluteTargetSpeed", value=f"{v:.6f}")


def _teleport(parent, lid, s):
    pos = ET.SubElement(ET.SubElement(parent, "TeleportAction"), "Position")
    ET.SubElement(pos, "LanePosition", roadId="1", laneId=str(lid), offset="0.0", s=f"{s:.3f}")


def xosc_name(spec: Spec, side: str) -> str:
    return f"{spec.case_id}_{side}.xosc"


def write_xosc(spec: Spec, side: str) -> Path:
    root = ET.Element("OpenSCENARIO")
    ET.SubElement(root, "FileHeader", revMajor="1", revMinor="2", date="2026-10-28T00:00:00",
                  author="P9 (AI-assisted)", description=f"{spec.case_id} [{side}] {spec.family}")
    pd = ET.SubElement(root, "ParameterDeclarations")
    ET.SubElement(pd, "ParameterDeclaration", name="ExtCtrl", parameterType="boolean", value="false")
    ET.SubElement(root, "CatalogLocations")
    ET.SubElement(ET.SubElement(root, "RoadNetwork"), "LogicFile", filepath=f"road_{side}.xodr")
    ents = ET.SubElement(root, "Entities")
    ego = ET.SubElement(ents, "ScenarioObject", name="Ego")
    _vehicle(ego, "ego", "car")
    ctrl = ET.SubElement(ET.SubElement(ego, "ObjectController"), "Controller", name="P9_ExternalController")
    ET.SubElement(ET.SubElement(ctrl, "Properties"), "Property", name="esminiController", value="ExternalController")
    for a in spec.actors:
        _vehicle(ET.SubElement(ents, "ScenarioObject", name=a.name), a.name.lower(), a.category)
    sb = ET.SubElement(root, "Storyboard")
    acts = ET.SubElement(ET.SubElement(sb, "Init"), "Actions")
    p = ET.SubElement(acts, "Private", entityRef="Ego")
    _teleport(ET.SubElement(p, "PrivateAction"), lane_id(spec.ego_lane, side), spec.ego_s0)
    _speed_action(ET.SubElement(p, "PrivateAction"), spec.ego_v0, 0.0)
    ET.SubElement(ET.SubElement(p, "PrivateAction"), "ControllerAction").append(
        ET.Element("ActivateControllerAction", longitudinal="$ExtCtrl", lateral="$ExtCtrl"))
    for a in spec.actors:
        p = ET.SubElement(acts, "Private", entityRef=a.name)
        _teleport(ET.SubElement(p, "PrivateAction"), lane_id(a.lane, side), a.s0)
        _speed_action(ET.SubElement(p, "PrivateAction"), a.v0, 0.0)
    story = ET.SubElement(sb, "Story", name="story")
    act = ET.SubElement(story, "Act", name="act")
    for a in spec.actors:
        if not a.events:
            continue
        mg = ET.SubElement(act, "ManeuverGroup", maximumExecutionCount="1", name=f"mg_{a.name}")
        ET.SubElement(ET.SubElement(mg, "Actors", selectTriggeringEntities="false"), "EntityRef", entityRef=a.name)
        man = ET.SubElement(mg, "Maneuver", name=f"m_{a.name}")
        for i, e in enumerate(a.events):
            ev = ET.SubElement(man, "Event", name=f"{a.name}_e{i}", priority="parallel")
            pa = ET.SubElement(ET.SubElement(ev, "Action", name=f"{a.name}_a{i}"), "PrivateAction")
            if e.kind == "speed":
                _speed_action(pa, e.value, e.param)
            else:
                lc = ET.SubElement(ET.SubElement(pa, "LateralAction"), "LaneChangeAction")
                ET.SubElement(lc, "LaneChangeActionDynamics", dynamicsShape="sinusoidal", value=f"{e.param}",
                              dynamicsDimension="time")
                ET.SubElement(ET.SubElement(lc, "LaneChangeTarget"), "AbsoluteTargetLane",
                              value=str(lane_id(int(e.value), side)))
            cond = ET.SubElement(ET.SubElement(ET.SubElement(ev, "StartTrigger"), "ConditionGroup"), "Condition",
                                 name=f"{a.name}_c{i}", delay="0", conditionEdge="none")
            ET.SubElement(ET.SubElement(cond, "ByValueCondition"), "SimulationTimeCondition", value=f"{e.t}",
                          rule="greaterOrEqual")
    st = ET.SubElement(ET.SubElement(ET.SubElement(act, "StartTrigger"), "ConditionGroup"), "Condition",
                       name="act_start", delay="0", conditionEdge="none")
    ET.SubElement(ET.SubElement(st, "ByValueCondition"), "SimulationTimeCondition", value="0.0", rule="greaterOrEqual")
    stop = ET.SubElement(ET.SubElement(ET.SubElement(sb, "StopTrigger"), "ConditionGroup"), "Condition",
                         name="end", delay="0", conditionEdge="none")
    ET.SubElement(ET.SubElement(stop, "ByValueCondition"), "SimulationTimeCondition", value=f"{spec.t_end}",
                  rule="greaterThan")
    ET.indent(root, space="  ")
    path = SCEN_DIR / xosc_name(spec, side)
    comment = (f"\n  {spec.case_id} [{side}]: {spec.description}\n"
               f"  Lane indices of the spec mapped to lane ids for {side} (RHT: -index, LHT: +index).\n"
               f"  ExtCtrl=true hands the Ego to the ExternalController (Python closed loop, sim/runner.py).\n"
               f"  Generated by scripts/make_scenarios.py - do not edit by hand.\n")
    path.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<!--' + comment + '-->\n'
                    + ET.tostring(root, encoding="unicode") + "\n", encoding="utf-8")
    return path


def lane_ids_in_xosc(path: Path) -> list[int]:
    """All laneId / AbsoluteTargetLane values in a written scenario (used by the mirror test)."""
    root = ET.parse(path).getroot()
    ids = [int(e.get("laneId")) for e in root.iter("LanePosition")]
    ids += [int(e.get("value")) for e in root.iter("AbsoluteTargetLane")]
    return ids


# ----------------------------------------------------------------------------- the scenario set
KPH = 1.0 / 3.6


def scenario_specs() -> list[Spec]:
    specs = []
    # F1: cut-in from the overtaking-side lane (1) or from the kerb-side lane (3) into the ego lane (2),
    # followed by braking of the cutting-in vehicle.
    for code, lane, cat, desc in (("OS", 1, "car", "超车侧切入"), ("KS", 3, "car", "路缘侧切入"),
                                  ("MC", 3, "motorbike", "摩托车从路缘侧切入")):
        cutter = Actor("Cutter", cat, lane, 112.0, 110 * KPH,
                       (Event(1.0, "lane", 2, 2.5), Event(2.0, "speed", 40 * KPH, 5.0)))
        specs.append(Spec(f"F1_CUTIN_{code}", "F1 切入", f"{desc}：110 km/h，1.0 s 时开始 2.5 s 变道，2.0 s 起以 5 m/s² 减到 40 km/h",
                          2, 100.0, 100 * KPH, (cutter,), t_end=12.0))
    # F2: slower vehicle in the overtaking lane ahead, own lane free -> may the ego pass it on the inside?
    slow = Actor("SlowOT", "car", 1, 160.0, 80 * KPH)
    specs.append(Spec("F2_UNDERTAKE", "F2 不得内侧超车", "超车道前方 60 m 有 80 km/h 慢车，本车道空，本车设定 110 km/h",
                      2, 100.0, 100 * KPH, (slow,), t_end=25.0))
    # F3: slow lead in the ego lane, fast vehicle approaching in the overtaking lane -> system-initiated
    # overtaking lane change with a UN R171 6.2.4 rear check.
    lead = Actor("Lead", "car", 2, 170.0, 80 * KPH)
    fast = Actor("FastOT", "car", 1, 0.0, 130 * KPH)
    specs.append(Spec("F3_OVERTAKE", "F3 系统发起超车变道", "本车道前方 70 m 有 80 km/h 前车，超车道后方 100 m 有 130 km/h 来车",
                      2, 100.0, 100 * KPH, (lead, fast), t_end=30.0))
    return specs


def write_all() -> list[Path]:
    out = [write_road(side) for side in SIDES]
    for spec in scenario_specs():
        for side in SIDES:
            out.append(write_xosc(spec, side))
    return out
